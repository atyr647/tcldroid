#!/usr/bin/env python3
"""Render android-host/AndroidManifest.xml.in and the generated res/Java for one app.

usage: render-manifest.py OUTDIR --orientation O --icon ICON --permissions "p1 p2" --backup 0|1 --version V
Writes OUTDIR/AndroidManifest.xml and OUTDIR/BuildInfo.java.
"""
import argparse, os, re, sys

ap = argparse.ArgumentParser()
ap.add_argument("outdir")
ap.add_argument("--template", required=True)
ap.add_argument("--orientation", default="unspecified")
ap.add_argument("--icon", default="@drawable/app_icon")
ap.add_argument("--permissions", default="")
ap.add_argument("--backup", default="0")
ap.add_argument("--version", required=True)
a = ap.parse_args()

ORIENT = {"auto": "unspecified", "unspecified": "unspecified", "portrait": "portrait", "landscape": "landscape",
          "sensor": "fullSensor", "sensor-portrait": "sensorPortrait", "sensor-landscape": "sensorLandscape"}
if a.orientation not in ORIENT:
    sys.exit("orientation must be one of: " + ", ".join(sorted(ORIENT)))
perms = []
for p in a.permissions.split():
    if not re.fullmatch(r"[A-Za-z][A-Za-z0-9_]*(\.[A-Za-z][A-Za-z0-9_]*)+", p):
        sys.exit("invalid permission name: %r" % p)
    if p not in ("android.permission.INTERNET", "android.permission.VIBRATE") and p not in perms:
        perms.append(p)
extra = "".join('    <uses-permission android:name="%s" />\n' % p for p in perms)

t = open(a.template, encoding="utf-8").read()
t = (t.replace("@EXTRA_PERMISSIONS@\n", extra).replace("@ICON@", a.icon).replace("@ORIENTATION@", ORIENT[a.orientation])
      .replace("@ALLOW_BACKUP@", "true" if a.backup == "1" else "false"))
os.makedirs(a.outdir, exist_ok=True)
open(os.path.join(a.outdir, "AndroidManifest.xml"), "w", encoding="utf-8").write(t)
jd = os.path.join(a.outdir, "java", "dev", "tcldroid", "host")
os.makedirs(jd, exist_ok=True)
open(os.path.join(jd, "BuildInfo.java"), "w").write(
    'package dev.tcldroid.host;\n\n/** Generated by tools/render-manifest.py from the VERSION file. */\n'
    'final class BuildInfo {\n    static final String VERSION = "%s";\n\n    private BuildInfo() {}\n}\n' % a.version)
