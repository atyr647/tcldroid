#!/usr/bin/env bash
# Build libtk9.0.so with the Android platform layer.
#   usage: tools/build-tk.sh host         # build machine (glibc): fast dev/test loop, FreeType text engine
#          tools/build-tk.sh <abi>        # Android (arm64-v8a, x86_64): needs build-tcl-android.sh first
# Output: build/tk-<mode>/libtk9.0.so.  Symbols not implemented yet get generated stubs
# that log "not implemented: NAME" when called (build/tk-<mode>/gen/tkAndroidStubs.c).
. "$(dirname "$0")/env.sh"
mode="${1:?usage: build-tk.sh host|<abi>}"
"$TCLDROID_ROOT/tools/fetch-upstream.sh" >/dev/null
TK="$BUILD_DIR/src/tk$TK_VERSION"; TCLSRC="$BUILD_DIR/src/tcl$TCL_VERSION"
# The overlay is under active development: always re-sync it.
mkdir -p "$TK/android"; cp -a "$TCLDROID_ROOT/tk-android/android/." "$TK/android/"

OUT="$BUILD_DIR/tk-$mode${SUFFIX:-}"; mkdir -p "$OUT/obj" "$OUT/gen"
if [ "$mode" = host ]; then
  "$TCLDROID_ROOT/tools/build-host-tcl.sh" >/dev/null
  TCLINST="$BUILD_DIR/install/host"
  CC=gcc; LINKLIBS="-lfreetype -lm -lpthread"
  DEFS="-DTK_ANDROID_PORT -DTKA_TEST_FREETYPE $(pkg-config --cflags freetype2)"
  CFLAGS_EXTRA="-g -O1"
  # SANITIZE=1 SUFFIX=-asan: AddressSanitizer build for hunting memory bugs.
  [ -z "${SANITIZE:-}" ] || { CFLAGS_EXTRA="$CFLAGS_EXTRA -fsanitize=address -fno-omit-frame-pointer"; LINKLIBS="$LINKLIBS -fsanitize=address"; }
else
  "$TCLDROID_ROOT/tools/fetch-ndk.sh" >/dev/null
  TCLINST="$BUILD_DIR/install/android-$mode"
  [ -f "$TCLINST/lib/libtclstub.a" ] || "$TCLDROID_ROOT/tools/build-tcl-android.sh" "$mode"
  TOOL="$NDK_HOME/toolchains/llvm/prebuilt/linux-x86_64/bin"
  CC="$TOOL/$(abi_triple "$mode")${ANDROID_MIN_API}-clang"; LINKLIBS="-llog -lm -ldl -Wl,-z,max-page-size=16384"
  DEFS="-DANDROID"
  CFLAGS_EXTRA="-O2"
fi
{ echo '#define TK_VERSION_UUID \'; cat "$TK/manifest.uuid"; echo; } > "$OUT/gen/tkUuid.h"
FLAGS="$DEFS -DBUILD_tk -DUSE_TCL_STUBS -DTK_LIBRARY=\"//zipfs:/lib/tk\" -fPIC -fvisibility=default -w $CFLAGS_EXTRA \
  -I$TK/android -I$TK/generic -I$TK/generic/ttk -I$TK/xlib -I$TK/bitmaps -I$TK/unix -I$OUT/gen \
  -I$TCLINST/include -I$TCLSRC/generic"

compile_one() {
  src="$1"; o="$OUT/obj/$(basename "$(dirname "$src")")_$(basename "$src" .c).o"
  if [ ! -f "$o" ] || [ "$src" -nt "$o" ] || [ -n "${FORCE:-}" ] || [ "$TK/android/tkAndroidPriv.h" -nt "$o" ]; then
    $CC $FLAGS -c "$src" -o "$o" 2>"$o.err" || { echo "FAILED: $src"; sed 's/^/    /' "$o.err" | head -25; return 1; }
  fi
}
export -f compile_one; export CC FLAGS OUT TK FORCE
log "compiling Tk for $mode"
"$TCLDROID_ROOT/tools/tk-sources.sh" --with-android | xargs -P"$(nproc)" -I{} bash -c 'compile_one {}' 2>&1 | tee "$OUT/compile.log" | head -80
[ -z "$(grep FAILED "$OUT/compile.log")" ] || die "compile errors (see above)"

link() { $CC -shared -o "$OUT/libtk9.0.so" "$OUT"/obj/*.o ${1:-} -L"$TCLINST/lib" -ltclstub $LINKLIBS; }
# 1) link permissively; 2) find what is still undefined; 3) stub it; 4) relink strictly.
rm -f "$OUT/obj/gen_stubs.o"   # never link stubs from a previous run
log "linking"
$CC -shared -o "$OUT/libtk9.0.so" "$OUT"/obj/*.o -L"$TCLINST/lib" -ltclstub $LINKLIBS -Wl,--no-undefined 2>"$OUT/link.err" || true
{ grep -o "undefined reference to \`[A-Za-z0-9_]*'\|undefined symbol: [A-Za-z0-9_]*" "$OUT/link.err" || true; } | sed "s/.*[\`: ]//; s/'//" | sort -u > "$OUT/unimplemented.txt"
{ echo '/* GENERATED by tools/build-tk.sh: stubs for platform functions not implemented yet. */'
  echo 'void TkAStubCalled(const char *name);'
  while read -r s; do [ -n "$s" ] && echo "long $s() { TkAStubCalled(\"$s\"); return 0; }"; done < "$OUT/unimplemented.txt"
} > "$OUT/gen/tkAndroidStubs.c"
$CC $FLAGS -c "$OUT/gen/tkAndroidStubs.c" -o "$OUT/obj/gen_stubs.o"
$CC -shared -o "$OUT/libtk9.0.so" "$OUT"/obj/*.o -L"$TCLINST/lib" -ltclstub $LINKLIBS -Wl,--no-undefined 2>"$OUT/link2.err" \
  || { head -20 "$OUT/link2.err"; die "link failed"; }
# Append Tk's script library as a zip (mounted at //zipfs:/lib/tk by TkpInit).
HOSTTCL="$BUILD_DIR/install/host/bin/tclsh9.0"
[ -x "$HOSTTCL" ] || "$TCLDROID_ROOT/tools/build-host-tcl.sh" >/dev/null
STAGE="$OUT/tk_library"; rm -rf "$STAGE"; mkdir -p "$STAGE"; cp -a "$TK/library/." "$STAGE/"
cp "$OUT/libtk9.0.so" "$OUT/libtk9.0.so.plain"
LD_LIBRARY_PATH="$BUILD_DIR/install/host/lib" "$HOSTTCL" <<TCL
zipfs mkimg {$OUT/libtk9.0.so} {$STAGE} {$STAGE} {} {$OUT/libtk9.0.so.plain}
TCL
log "built $OUT/libtk9.0.so ($(du -h "$OUT/libtk9.0.so" | cut -f1) incl. script library); $(wc -l < "$OUT/unimplemented.txt") functions still stubbed (see $OUT/unimplemented.txt)"
